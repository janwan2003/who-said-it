// Same prompt for every group on a given day; a fixed shuffle so neighbours in the list don't repeat themes.
const EPOCH = Date.UTC(2026, 10, 21); // 2026-11-21
export function promptIndexFor(day) {
  const [y, m, d] = day.split('-').map(Number);
  const n = Math.round((Date.UTC(y, m - 1, d) - EPOCH) / 86400000);
  const len = PROMPTS.length;
  const i = ((n % len) + len) % len;
  return (i * 37 + 11) % len; // 37 is coprime with the list length, so this is a permutation
}
